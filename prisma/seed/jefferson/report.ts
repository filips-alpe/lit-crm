/**
 * REPORT.md, rendered from the dataset. Every number and every listed item comes from the
 * generator; nothing in the output is typed by hand.
 */
import type { Dataset, LogRow } from './dataset';
import { ENTITY_KEY_PREFIX } from './dataset';
import type { PartId } from './split';
import { ENTITY_TYPE_CODES } from './types';

const PARTS: PartId[] = [
  'editorial',
  'autobiography',
  'anas',
  'notes-on-virginia',
  'parliamentary-manual',
];

const pct = (a: number, b: number) => (b === 0 ? '0.0%' : `${((100 * a) / b).toFixed(1)}%`);
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, '⏎');
const code = (s: string) => '`' + s.replace(/`/g, "'").replace(/\n/g, '⏎') + '`';

function table(head: string[], rows: (string | number)[][]): string {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map((c) => esc(String(c))).join(' | ')} |`),
  ].join('\n');
}

const count = <K>(items: K[]): Map<K, number> => {
  const m = new Map<K, number>();
  for (const i of items) m.set(i, (m.get(i) ?? 0) + 1);
  return m;
};

const sorted = <K>(m: Map<K, number>): [K, number][] =>
  [...m.entries()].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));

/** Words common enough in English prose that a line without any is not English prose. */
const FUNCTION_WORDS = new Set(
  'the of and to in is that it he was for with be by as at on this which are from or not his have an'.split(
    ' ',
  ),
);

export type GarbledLine = { rawLine: number; part: PartId; text: string; likely: boolean };

/** Lines whose long words are mostly unique in the whole scan. A heuristic, reported as such. */
export function garbledLines(d: Dataset): GarbledLine[] {
  const { lines, ctx, split } = d.analysis;
  const words = (l: string) => [...l.matchAll(/\p{L}{3,}/gu)].map((m) => m[0].toLowerCase());
  const freq = new Map<string, number>();
  lines.forEach((l, i) => {
    if (ctx.furniture[i]) return;
    for (const w of words(l)) freq.set(w, (freq.get(w) ?? 0) + 1);
  });
  const partAt = (line: number): PartId => {
    let lo = 0;
    let hi = split.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (split[mid].start <= line) lo = mid;
      else hi = mid - 1;
    }
    return split[lo].part;
  };
  const out: GarbledLine[] = [];
  lines.forEach((l, i) => {
    if (ctx.furniture[i]) return;
    const t = l.trim();
    if (t.replace(/\s/g, '').length < 6) return;
    const ws = words(t);
    if (ws.length < 2) return;
    const rare = ws.filter((w) => freq.get(w) === 1).length;
    if (rare / ws.length < 0.6) return;
    const english = ws.some((w) => FUNCTION_WORDS.has(w));
    out.push({ rawLine: i + 1, part: partAt(i + 1), text: t, likely: !english });
  });
  return out;
}

const HYPHEN_KINDS = new Set(['hyphen-join', 'hyphen-keep']);

export function renderReport(d: Dataset): string {
  const { records, entities, mentions, cleanupLog } = d;
  const a = d.analysis;
  const out: string[] = [];
  const h = (n: number, t: string) => out.push('', `${'#'.repeat(n)} ${t}`, '');
  const p = (...s: string[]) => out.push(...s);

  out.push(
    '# Jefferson corpus report',
    '',
    'Generated by `tsx prisma/seed/jefferson/generate.ts` from the cached Internet Archive OCR of',
    'Lipscomb & Bergh, *The Writings of Thomas Jefferson* (1905), vols. I and II. Every number below is computed;',
    'nothing is typed by hand. Line numbers are 1-based lines of the `_djvu.txt` file.',
  );

  // ------------------------------------------------------------ counts
  h(2, 'Counts');
  const byType = count(records.map((r) => r.type));
  p(
    `Records: **${records.length}**, covering all ${a.lines.length} raw lines (each in exactly one record).`,
    '',
    table(
      ['record type', 'records'],
      sorted(byType).map(([t, n]) => [t, n]),
    ),
    '',
    table(
      ['part', 'records', 'raw lines'],
      PARTS.map((part) => {
        const rs = records.filter((r) => r.part === part);
        return [part, rs.length, rs.reduce((s, r) => s + r.rawLineEnd - r.rawLineStart + 1, 0)];
      }),
    ),
    '',
    `Entities with at least one mention: **${entities.length}** of ${a.gazetteer.entities.length} in the gazetteer.`,
    '',
    table(
      ['entity type', 'entities', 'mentions'],
      ENTITY_TYPE_CODES.map((t) => {
        const es = entities.filter((e) => e.type === t);
        return [t, es.length, es.reduce((s, e) => s + e.mentionCount, 0)];
      }),
    ),
    '',
    `Mentions (linked): **${mentions.length}**.`,
  );
  const unused = a.gazetteer.entities.filter(
    (e) => !entities.some((x) => x.key === ENTITY_KEY_PREFIX + e.key),
  );
  p(
    '',
    `Gazetteer entries without a mention (kept as ambiguity candidates or for completeness): ${unused.length}` +
      (unused.length ? ` (${unused.map((e) => code(e.key)).join(', ')}).` : '.'),
  );

  // ------------------------------------------------------------ link rate
  h(2, 'Link rate');
  const linked = mentions.length;
  const ambiguousUnlinked = a.ambiguousHits.length;
  const unmatchedTotal = [...a.unmatched.values()].reduce((s, n) => s + n, 0);
  p(
    'Link rate = linked / (linked + ambiguous-unlinked + unmatched capitalised name candidates).',
    'A *linked* mention is a gazetteer surface the linker resolved to one entity. *Ambiguous-unlinked* is a surface',
    'listed under `ambiguous` (or a part-scoped surname left unresolved in another part) that was deliberately not linked.',
    '*Unmatched* is a run of capitalised words that looks like a name (see `candidates.ts`: sentence openers, calendar words,',
    'offices and nationality adjectives excluded) that overlaps neither. Front-matter records are not counted.',
    '',
    table(
      ['', 'count'],
      [
        ['linked', linked],
        ['ambiguous-unlinked', ambiguousUnlinked],
        ['unmatched name candidates', unmatchedTotal],
        ['**link rate**', `**${pct(linked, linked + ambiguousUnlinked + unmatchedTotal)}**`],
      ],
    ),
    '',
    table(
      ['part', 'linked', 'ambiguous-unlinked', 'unmatched', 'link rate'],
      PARTS.map((part) => {
        const l = a.linkedByPart.get(part) ?? 0;
        const am = a.ambiguousByPart.get(part) ?? 0;
        const u = a.unmatchedByPart.get(part) ?? 0;
        return [part, l, am, u, pct(l, l + am + u)];
      }),
    ),
    '',
    'The rate is a floor: the unmatched count includes lone given names, citation fragments and OCR noise that no',
    'gazetteer should resolve.',
  );

  h(3, 'Most mentioned entities');
  p(
    table(
      ['entity', 'type', 'mentions'],
      [...entities]
        .sort((x, y) => y.mentionCount - x.mentionCount || x.key.localeCompare(y.key))
        .slice(0, 25)
        .map((e) => [e.title, e.type, e.mentionCount]),
    ),
  );

  h(3, 'Surfaces found in the text, by form');
  const surfaceByEntity = new Map<string, Map<string, number>>();
  for (const m of mentions) {
    const bySurface = surfaceByEntity.get(m.entityKey) ?? new Map<string, number>();
    bySurface.set(m.surface, (bySurface.get(m.surface) ?? 0) + 1);
    surfaceByEntity.set(m.entityKey, bySurface);
  }
  p(
    'The twelve most mentioned entities with the forms the linker matched (name resolution):',
    '',
    table(
      ['entity', 'forms matched (count)'],
      [...entities]
        .sort((x, y) => y.mentionCount - x.mentionCount || x.key.localeCompare(y.key))
        .slice(0, 12)
        .map((e) => [
          e.title,
          sorted(surfaceByEntity.get(e.key)!)
            .map(([s, n]) => `${s} (${n})`)
            .join('; '),
        ]),
    ),
  );

  // ------------------------------------------------------------ ambiguous
  h(2, 'Ambiguous mentions left unlinked');
  const byName = new Map(a.gazetteer.entities.map((e) => [e.key, e.name]));
  const ambCounts = count(a.ambiguousHits.map((x) => x.surface));
  const reason = new Map(a.gazetteer.ambiguous.map((x) => [x.surface, x]));
  p(
    `${a.gazetteer.ambiguous.length} surfaces are declared ambiguous; ${ambCounts.size} of them occur in the text,`,
    `${ambiguousUnlinked} times in all. Each stays plain text.`,
    '',
    table(
      ['surface', 'occurrences left unlinked', 'candidates', 'why'],
      sorted(ambCounts).map(([s, n]) => {
        const r = reason.get(s);
        return [
          s,
          n,
          (r?.candidates ?? []).map((k) => byName.get(k) ?? k).join('; '),
          r?.reason ?? '(part-scoped surname unresolved here)',
        ];
      }),
    ),
  );
  const never = a.gazetteer.ambiguous.filter((x) => !ambCounts.has(x.surface));
  if (never.length)
    p(
      '',
      `Declared ambiguous but absent from the text: ${never.map((x) => code(x.surface)).join(', ')}.`,
    );

  h(2, 'Top unlinked surfaces');
  p(
    'Capitalised name candidates that matched nothing in the gazetteer, most frequent first (top 60).',
    '',
    table(
      ['surface', 'count'],
      sorted(a.unmatched)
        .slice(0, 60)
        .map(([s, n]) => [s, n]),
    ),
  );

  // ------------------------------------------------------------ cleanup / OCR
  h(2, 'Cleanup and OCR issues');
  const totals = a.stats.reduce(
    (t, s) => ({
      furnitureLines: t.furnitureLines + s.furnitureLines,
      blocks: t.blocks + s.blocks,
      proseBlocks: t.proseBlocks + s.proseBlocks,
      verbatimBlocks: t.verbatimBlocks + s.verbatimBlocks,
      hyphenJoined: t.hyphenJoined + s.hyphenJoined,
      hyphenKept: t.hyphenKept + s.hyphenKept,
      pageMerges: t.pageMerges + s.pageMerges,
      footnoteBlocks: t.footnoteBlocks + s.footnoteBlocks,
    }),
    {
      furnitureLines: 0,
      blocks: 0,
      proseBlocks: 0,
      verbatimBlocks: 0,
      hyphenJoined: 0,
      hyphenKept: 0,
      pageMerges: 0,
      footnoteBlocks: 0,
    },
  );
  const furnitureByKind = count(
    cleanupLog
      .filter((l) => !HYPHEN_KINDS.has(l.kind) && l.kind !== 'page-merge')
      .map((l) => l.kind),
  );
  p(
    `Raw lines: ${a.lines.length}; non-blank: ${a.lines.filter((l) => l.trim() !== '').length}; blocks after cleanup: ${totals.blocks} (${totals.proseBlocks} unwrapped prose, ${totals.verbatimBlocks} kept line-for-line as tables or short lines).`,
    '',
    table(
      ['logged change', 'count'],
      [
        ...sorted(furnitureByKind).map(([k, n]) => [`${k} lines removed`, n]),
        ['line-end hyphens joined', totals.hyphenJoined],
        ['line-end hyphens kept', totals.hyphenKept],
        ['paragraphs merged across a page break', totals.pageMerges],
      ],
    ),
    '',
    `Every change is logged with its raw line in \`cleanup-log.json\` (${cleanupLog.length} entries).`,
    '',
    table(
      ['issue left in the text (never corrected)', 'count'],
      [
        ['footnote blocks left in place, verbatim', totals.footnoteBlocks],
        [
          'raw lines whose characters span two leaves (assigned to their first leaf)',
          a.map.straddling.length,
        ],
        [
          'records whose boundary heading is OCR-damaged (title read from position in the series)',
          records.filter((r) => /printed heading "/.test(r.note ?? '')).length,
        ],
        [
          'record titles repaired from OCR damage in the printed question (text untouched)',
          records.filter((r) => /corrects OCR damage/.test(r.note ?? '')).length,
        ],
        [
          'Anas memoranda with no full date in the text (no date recorded)',
          records.filter(
            (r) => r.part === 'anas' && r.type === 'memorandum' && r.date === undefined,
          ).length,
        ],
        [
          'autobiography records titled by the dataset (text has no headings)',
          records.filter(
            (r) =>
              /^Title supplied by the dataset/.test(r.note ?? '') && r.part === 'autobiography',
          ).length,
        ],
      ],
    ),
  );

  const SPACED_NAME = /\bJ ?[Ee] ?F ?F ?[Ee] ?R ?S ?[Oo] ?N\b/i;
  const letterspaced = a.lines
    .filter((l, i) => !a.ctx.furniture[i] && SPACED_NAME.test(l))
    .map((l) => SPACED_NAME.exec(l)![0])
    .filter((m) => m.includes(' '));
  p(
    '',
    `Letterspaced forms of the name remain in the text: ${letterspaced.length} ${letterspaced.length === 1 ? 'line' : 'lines'}` +
      (letterspaced.length ? ` (for example ${code(letterspaced[0])})` : '') +
      '. They are not corrected and are not linked.',
  );

  const garbled = garbledLines(d);
  const likely = garbled.filter((g) => g.likely);
  h(3, 'Garbled lines');
  p(
    'Lines (outside removed furniture) in which at least 60% of the words of three or more letters occur exactly once in',
    'the whole scan. This also catches quoted Latin, French and Old English, so a second count keeps only lines',
    'with no common English function word. Rotated table leaves produce the worst of it. All stay verbatim.',
    '',
    table(
      ['part', 'candidate lines', 'of which no English function word'],
      PARTS.map((part) => [
        part,
        garbled.filter((g) => g.part === part).length,
        likely.filter((g) => g.part === part).length,
      ]),
    ),
    '',
    `Total: ${garbled.length} candidate lines, ${likely.length} likely garbled. A spread sample of the likely ones:`,
    '',
    ...likely
      .filter((_, i) => i % Math.max(1, Math.floor(likely.length / 12)) === 0)
      .slice(0, 12)
      .map((g) => `- line ${g.rawLine}: ${code(g.text.slice(0, 70))}`),
  );

  // ------------------------------------------------------------ hyphen audit
  h(2, 'Hyphen audit');
  const hyph: LogRow[] = cleanupLog.filter((l) => HYPHEN_KINDS.has(l.kind));
  const byReason = count(hyph.map((l) => `${l.kind} / ${l.reason}`));
  p(
    `${hyph.length} line-end hyphens were decided by the rule (joined form attested elsewhere: join; only the hyphenated`,
    'form attested: keep; neither: reviewed list, number compounds and compound left parts keep, otherwise join).',
    'Every decision is in `cleanup-log.json`.',
    '',
    table(
      ['decision / reason', 'count'],
      sorted(byReason).map(([k, n]) => [k, n]),
    ),
  );
  const unrelated = hyph.filter((l) => l.reason === 'unrelated-words');
  h(3, 'Unrelated-word breaks');
  p(
    `${unrelated.length} breaks join two different words (the OCR lost text after the hyphen); the hyphen stays and the`,
    'break becomes a space:',
    '',
    table(
      ['line', 'raw', 'result'],
      unrelated.map((l) => [l.rawLine, code(l.raw), code(l.result)]),
    ),
  );
  const defaults = hyph.filter((l) => l.reason === 'default-join');
  h(3, 'Default joins');
  p(
    `${defaults.length} breaks had neither form attested and were joined by default. Every one is listed so that each`,
    'can be audited against its raw lines.',
    '',
    table(
      ['line', 'raw', 'result'],
      defaults.map((l) => [l.rawLine, code(l.raw), code(l.result)]),
    ),
  );

  return out.join('\n') + '\n';
}
